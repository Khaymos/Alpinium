use crate::config::Config;
use smithay::reexports::{calloop::EventLoop, wayland_server::Display};
use std::{ffi::OsString, path::PathBuf, process::Command};

pub fn run(
    config: Config,
    config_source: Option<PathBuf>,
    command: Option<OsString>,
) -> Result<(), Box<dyn std::error::Error>> {
    init_logging();

    let source = config_source
        .as_ref()
        .map(|path| path.display().to_string())
        .unwrap_or_else(|| "built-in defaults".to_string());

    let mut event_loop: EventLoop<AlpiniumState> = EventLoop::try_new()?;
    let display: Display<AlpiniumState> = Display::new()?;
    let mut state = AlpiniumState::new(&mut event_loop, display, config);

    winit::init_winit(&mut event_loop, &mut state)?;

    println!("Alpinium {} — nested Wayland compositor", env!("CARGO_PKG_VERSION"));
    println!("Configuration: {source}");
    println!("Configured layout mode: {}", state.config.mode);
    println!("Wayland socket: {}", state.socket_name.to_string_lossy());
    println!("Note: tiling/floating layout policy is not implemented yet.");

    if let Some(program) = command {
        println!("Launching nested client: {}", program.to_string_lossy());
        Command::new(&program)
            .env("WAYLAND_DISPLAY", &state.socket_name)
            .spawn()?;
    } else {
        println!("No client launched. Start one with the Wayland socket shown above.");
    }

    event_loop.run(None, &mut state, move |_| {
        // Alpinium's nested compositor event loop.
    })?;

    Ok(())
}

fn init_logging() {
    if let Ok(env_filter) = tracing_subscriber::EnvFilter::try_from_default_env() {
        tracing_subscriber::fmt().with_env_filter(env_filter).init();
    } else {
        tracing_subscriber::fmt().init();
    }
}
